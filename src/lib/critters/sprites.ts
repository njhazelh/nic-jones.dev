// The critters' art, one character per pixel. '.' is transparent; every other
// character is a key in that critter's palette. A palette value is a theme
// token (fg, muted, accent, bg, sunk) or a 'light:#hex|dark:#hex' pair.
// Every frame of a critter has the same size. scripts/check-sprites.mjs checks
// all of this on every build, and the colophon counts the frames.
//
// Only erasable TypeScript here, so Node can import this file directly.

export type Palette = Record<string, string>;
export interface Critter {
  palette: Palette;
  frames: Record<string, string[]>;
  /** Halo colour drawn around the silhouette in the dark theme */
  glow?: string;
}

